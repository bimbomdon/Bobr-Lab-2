# Просим пользователя ввести год
god = int(input("Введите год: "))

# Условие для проверки на високосность
visokosny = (god % 4 == 0 and god % 100 != 0) or (god % 400 == 0)

# 2. Определяем количество дней с помощью if/else
if visokosny:
    dni_v_godu = 366
    status = "високосный"
else:
    dni_v_godu = 365
    status = "не високосный"

# 3. Аналог switch/case для вывода сообщения
# В Python нет конструкции switch, поэтому используют словарь (dictionary)
# Это как переключатель: ключ - это значение переменной, значение - то, что вернем.

def get_message(dni):
    # Создаем "переключатель"
    cases = {
        365: "Обычный год",
        366: " Год високосный.",
    }
    # .get() берет значение по ключу. Если ключа нет, вернет второй аргумент (по умолчанию)
    return cases.get(dni, "Что-то пошло не так, такого количества дней не бывает.")



# Вывод результатов
print(f"Год {god} - {status}.")
print(f"В нем {dni_v_godu} дней.")


# Вводим номер месяца
month = int(input("Введите номер месяца (1-12): "))

# Проверка на корректность ввода
if month < 1 or month > 12:
    print("Ошибка: такого месяца не существует!")
else:
    # Делаем определение времени года через сложные условия 
    if month in [12, 1, 2]:
        season = "Зима"
    elif month in [3, 4, 5]:
        season = "Весна"
    elif month in [6, 7, 8]:
        season = "Лето"
    else:
        season = "Осень"

    # Определение количества дней через словарь 
    # Ключ — номер месяца, Значение — количество дней
    days_map = {
        1: 31, 2: 28, 3: 31, 4: 30, 
        5: 31, 6: 30, 7: 31, 8: 31, 
        9: 30, 10: 31, 11: 30, 12: 31
    }
    
    days = days_map[month]

    # Вывод результата
    print(f"Месяц: {month}")
    print(f"Время года: {season}")
    print(f"Количество дней: {days}")
    
    # Маленькое уточнение про февраль
    if month == 2:
        print("(Примечание: в високосный год в феврале 29 дней)")
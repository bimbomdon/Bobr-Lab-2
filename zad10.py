# Тарифы: цена за минуту
TARIF_1 = 5.0   # Первый тариф: 5 рублей/мин
TARIF_2 = 3.0   # Второй тариф: 3 рубля/мин
SKIDKA = 0.20   # Скидка 20% в выходные

# Вводим данные
minutes = float(input("Длительность разговора (минуты): "))
tarif = int(input("Выберите тариф (1 или 2): "))
day = int(input("День недели (1-пн ... 7-вс): "))

#  Проверка корректности ввода через вложенные if
if minutes <= 0:
    print("Ошибка: длительность должна быть больше нуля")
else:
    if tarif != 1 and tarif != 2:
        print("Ошибка: выберите тариф 1 или 2")
    else:
        if day < 1 or day > 7:
            print("Ошибка: день недели от 1 до 7")
        else:
            # Выбираем цену за минуту
            if tarif == 1:
                price = TARIF_1
            else:
                price = TARIF_2
            
            #  Считаем базовую стоимость
            cost = price * minutes
            
            # Проверяем, выходной ли день
            if day >= 6:
                # Применяем скидку
                cost = cost - cost * SKIDKA
                print(f"Сегодня выходной — скидка {SKIDKA*100:.0f}%!")
            
            # Выводим итог
            print(f"Стоимость разговора: {cost:.2f} руб.")
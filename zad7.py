x = float(input("Введите координату X: "))
y = float(input("Введите координату Y: "))

#  Сначала проверяем особые случаи (оси и центр)
if x == 0 and y == 0:
    print("Точка находится в начале координат (0, 0)")
else:
    if x == 0:
        print("Точка лежит на оси Y")
    else:
        if y == 0:
            print("Точка лежит на оси X")
        else:
            # Определяем четверть через вложенные условия
            if x > 0:
                # X положительный, теперь смотрим на Y
                if y > 0:
                    quarter = "I (первая)"
                else:
                    quarter = "IV (четвертая)"
            else:
                # X отрицательный, теперь смотрим на Y
                if y > 0:
                    quarter = "II (вторая)"
                else:
                    quarter = "III (третья)"
            
            print(f"Точка находится в {quarter} четверти")
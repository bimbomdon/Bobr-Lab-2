num = int(input("Введите целое трехзначное число: "))

# Берем абсолютное значение, чтобы минус не мешал проверке длины
abs_num = abs(num)

# Проверка: является ли число трёхзначным?
# Трёхзначные числа от 100 до 999 включительно
if 100 <= abs_num <= 999:
    
    # Извлекаем цифры с помощью деления и остатка
    # Остаток от деления на 10 дает последнюю цифру
    digit3 = abs_num % 10          # Единицы
    
    # Делим на 10 нацело, чтобы убрать последнюю цифру, потом снова берем остаток
    digit2 = (abs_num // 10) % 10  # Десятки
    
    # Делим на 100 нацело, чтобы получить первую цифру
    digit1 = abs_num // 100        # Сотни

    # Считаем сумму и произведение
    summa = digit1 + digit2 + digit3
    product = digit1 * digit2 * digit3

    print(f"Число {num} — трёхзначное.")
    print(f"Цифры: {digit1}, {digit2}, {digit3}")
    print(f"Сумма цифр: {summa}")
    print(f"Произведение цифр: {product}")

else:
    print("Ошибка: это не трёхзначное число!")
